/**
 * pi loads extensions with a loader that has no JSX. The board view is JSX (hooks/view/board.tsx, shared with the
 * Claude Code plugin), so this compiles it to plain JS once: `bun pi/scripts/gen-board.ts` writes pi/gen/board.js,
 * and `bun pi/scripts/gen-board.ts --check` fails when that file is out of date. A test runs the check.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(import.meta.path), '..', '..')
const SRC = join(ROOT, 'hooks', 'view', 'board.tsx')
const OUT = join(ROOT, 'pi', 'gen', 'board.js')

export function compileBoard(): string {
  const t = new Bun.Transpiler({
    loader: 'tsx',
    tsconfig: { compilerOptions: { jsx: 'react', jsxFactory: 'h', jsxFragmentFactory: 'Fragment' } } as never,
  })
  let js = t.transformSync(readFileSync(SRC, 'utf8'))
  // The file sits in pi/gen: './x' was hooks/view/x, '../x' was hooks/x.
  js = js.replace(/(from\s+)(["'])(\.\.?\/[^"']+)\2/g, (_m, kw: string, q: string, p: string) => `${kw}${q}${p.startsWith('./') ? `../../hooks/view/${p.slice(2)}` : `../../hooks/${p.slice(3)}`}${q}`)
  return `// Generated by pi/scripts/gen-board.ts from hooks/view/board.tsx. Do not edit.\nimport { h, Fragment } from '../ui/engine'\n${js}`
}

if (import.meta.main) {
  const out = compileBoard()
  if (process.argv.includes('--check')) {
    let cur = ''
    try {
      cur = readFileSync(OUT, 'utf8')
    } catch {}
    if (cur !== out) {
      console.error('pi/gen/board.js is out of date: run `bun pi/scripts/gen-board.ts`')
      process.exit(1)
    }
  } else writeFileSync(OUT, out)
}
